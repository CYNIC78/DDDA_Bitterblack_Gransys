#pragma once
/**
 * EnemyTuner — применение EntityCfg к живым врагам.
 *
 * ГЛАВНОЕ ПРАВИЛО: объекты ищутся ПО ИМЕНИ через DTI, а не по фиксированному
 * оффсету. Причина — наблюдение на трёх дампах одного гоблина:
 *
 *      слот +0x2B98:  CALM -> uPlayer      AGGRO -> uCmc
 *      uPlayer:       CALM +0x2B98         AGGRO/RETURN +0x2FA0
 *
 * То есть часть слотов тела переиспользуется под разные объекты в зависимости
 * от состояния. Захардкоженный оффсет рано или поздно попадёт не в тот объект
 * и мы запишем float в чужой указатель. Поэтому: сканируем тело, читаем имя
 * класса у игры, работаем только с совпавшим по имени.
 *
 * СТАБИЛЬНЫ (проверено 5 дампов): +0x2DC0 cActBank, +0x2DC8 Act, +0x2E64 cAICtrl.
 * НЕ СТАБИЛЕН: +0x2B98, +0x2FA0 и прочие «плавающие» слоты.
 *
 * РЕЖИМ DRY-RUN: по умолчанию ничего не пишет, только логирует намерение.
 * Включать запись осознанно, после того как поле подтверждено дампом.
 */

#include <stdint.h>

namespace EnemyTuner {

// Вызывать из тика (уже под контролем интервала). Дёшево.
void Tick();

// Разовый поиск рантайм-копии параметров зрения: ищем в теле врага и в его
// объектах float-тройку из em0100A.sn2 (1500 / 60 / 3000).
// Пишет находки в лог. Только чтение.
void ScanVisionParams();

// Hex-дамп окна +0x5900..+0x5B80, где нашлись параметры сенсора.
// Нужен, чтобы увидеть полную структуру записи, а не отдельные числа.
void DumpSensorWindow();

// Прочитать cCharParamEnemy из тела (+0x5870): таймеры поводка и масштаб.
// Проверяет сигнатуру структуры — не доверяет оффсету слепо.
void ReadCharParam();

// Диагностика: записать масштаб по кнопке и сразу перечитать.
// Различает «движок откатил» и «поле читается только при спавне».
// Целится в uEm0100 (гоблина), а не в "первого попавшегося".
void ForceScale(float v);

// Печать всего списка врагов с их текущим масштабом.
// Первый вопрос при любом «записал, а эффекта нет»: а кому записал?
void ListEnemies();

// Проверить удержание через несколько секунд после ForceScale.
// Пока держим, тик тело не трогает — значит изменения только от движка.
void CheckHold();

// Снять удержание, вернуть тело под управление тика.
void ReleaseHold();

// Hex+float дамп первых 0x100 байт тела и указателей в них.
// Проверка гипотезы «+0x60 — это масштаб»: вдруг настоящая
// location-структура лежит отдельным объектом (uCoord).
void DumpHead();

// UI-строка состояния для F12-панели.
const char* StatusLine();

// Индикатор ручного удержания: тело и значение (0 = удержания нет).
uintptr_t HeldBody();
float     HeldValue();

// --- покадровый сэмплер масштаба -------------------------------------------
// Отвечает на вопрос «кто меняет высоту»: наша запись статична (want зависит
// только от адреса тела), значит динамику пишет движок. Тик в 150 мс её
// не видит — нужен замер каждый кадр.
void SampleTick();      // вызывать из UI-колбэка = каждый кадр

// --- поиск анимируемых полей ------------------------------------------------
// Снимает ВСЁ тело (7408 float) каждый кадр и показывает, какие смещения
// меняются. Отвечает на вопрос «где рабочее значение, если +0x60 это база».
void StartFieldScan();
void StopFieldScan();

// Счётчики для UI
int TrackedCount();
int WriteCount();

} // namespace EnemyTuner
