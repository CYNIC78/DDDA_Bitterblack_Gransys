#pragma once
/**
 * MonsterAI::Director — режиссёр стороны монстров.
 *
 * МЕСТО В СИСТЕМЕ. Симметричен слою пешек. Обе стороны читают ОДНУ шину
 * (`CombatBus`) и каждая управляет своими примитивами:
 *
 *      CombatIntel + WorldScan  ->  CombatBus  ->  PawnAI::Orchestrator
 *                                             \->  MonsterAI::Director
 *
 * Пешки решают, как помогать игроку; режиссёр монстров решает, каким быть
 * противнику. Знание у них общее, выводы — разные. Так получается одна
 * система ИИ на обе стороны, а не два независимых хака.
 *
 * ЧТО ОН ДЕЛАЕТ. Ничего сам. Он смотрит на бой и раздаёт указания
 * примитивам:
 *
 *      Runtime::Tempo::SetOverride(body, loco, atk, ttlMs)   темп
 *      EnemyTuner                                            размер
 *      (дальше: дистанция, агрессия, память энкаунтеров)
 *
 * Правило слоя: режиссёр НЕ пишет в память игры напрямую. Никогда.
 * Всё, что он умеет, — читать шину и звать примитивы. Тогда любую его
 * ошибку видно как «неверное решение», а не как вылет.
 *
 * СОСТОЯНИЕ НА СЕЙЧАС: наблюдатель. Политик нет, записи нет, гейт
 * `[monsterAI] enabled` по умолчанию выключен. Это намеренно: сначала
 * убеждаемся, что режиссёр видит бой правильно, и только потом даём ему
 * право голоса.
 */

#include <stdint.h>

namespace MonsterAI {

// Что режиссёр видит про одну особь. Собирается каждый тик из скана мира
// и из шины; никаких собственных чтений памяти по «плавающим» оффсетам
// без проверки имени класса.
struct MonsterView {
    uintptr_t body;
    char      kind[16];       // uEm0100, uEm0101, ...
    char      act[40];        // текущее действие по DTI
    bool      attacking;      // действие классифицировано как атака
    bool      dead;
    float     distM;          // до Аризена, метры (-1 если неизвестно)
    float     locoFactor;     // итоговые множители из системы темпа
    float     atkFactor;
    uint32_t  seenMs;         // когда впервые увидели в этом бою
};

void Init();
void Shutdown();

// Зовётся из общего продуктового тика (UpdatePawnAI) под своим SEH.
void Tick();

// --- для панели -------------------------------------------------------------
bool        Enabled();
void        SetEnabled(bool on);
int         ViewCount();
const MonsterView* ViewAt(int i);
const char* Status();

// Снимок в лог: строка на монстра. Ручная кнопка, не автоматика —
// автоматический лог по тику засорил бы файл за минуту.
void DumpSnapshot();

} // namespace MonsterAI
