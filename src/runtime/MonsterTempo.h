// строже: все пять полей должны быть ровно 1.0. Отдельно от `animEnabled`,
// потому что это другой потребитель и другой риск.
//
// При снятии переопределения исходные значения ВОЗВРАЩАЮТСЯ: пешка не
// должна остаться с ускоренной анимацией после того, как рывок кончился.
void  SetAnimForOverrides(bool on);
bool  GetAnimForOverrides();

// ─────────────────────────── РАНГИ ОСОБЕЙ (85.40, имя с 85.42) ────────────
//
// ЗАЧЕМ. Раньше каждая особь вида тянула размер равномерно из коридора
// (1.00..1.15), и «кто тут главный» глазом не читалось: рядовой и вожак
// отличались на пару процентов. Поле 29.09 подтвердило, что числами короносец
// неотличим от рядового — единственный прибор у игрока это ГЛАЗ. Поэтому
// размер становится ступенью, а не лотереей:
//
//   новичок -> солдат -> ветеран -> элита -> мини-босс
//
// Ступень выбирается по адресу тела, детерминированно (в бою не мигает), но с
// солью сессии: между заходами пачка перетасовывается, и один и тот же слот не
// получает одну и ту же ступень всю жизнь.
//
// ГДЕ ЖИВУТ ЧИСЛА. В ini, потому что подбирать их придётся вам: глобальная
// секция [ranks] (вес, полоса размера и множитель атаки на ранг) и флаг
// [species.<kind>] ranks = on/off. Секции нет -> работают встроенные числа дня.
//
// ЧЕГО ЗДЕСЬ НЕТ. Потолков темпа по рангу (ветеран разгоняется сильнее) —
// это следующий шаг, он требует правки директора. И HP ранги не трогают.
struct RankStep {
    float weight;          // доля особей пачки на этой ступени (сумма = 1)
    float sizeMin, sizeMax;// полоса размера ступени
    float atk;             // множитель атаки (>= 1.0: ниже ванили не бывает)
    // 85.44: «ВО СКОЛЬКО РАЗ КРЕПЧЕ» — 1.0 = ваниль, больше = крепче.
    // Знак переводит код, а не игрок: сопротивления наложениям в игре лежат
    // множителем получаемого эффекта (меньше = крепче), а выносливости к
    // сбиванию — запасом (больше = крепче). Путать это нельзя, поэтому ключ
    // всегда читается как «крепче», в какую бы сторону ни лежало поле.
    float resist;          // сопротивления дебилитациям (горение, яд, сон, ...)
    float stand;           // отшатывание и сбивание с ног
};

enum { kRankSteps = 5 };

struct RanksNumbers {
    bool       enabled;              // [species.<kind>] ranks = on/off
    // 85.52: ранги МОГУТ работать без размера. Волк — ровно такой случай:
    // владелец принял ранги как инструмент, но рост волка менять нельзя
    // («волки-гиганты нелепо»), поэтому у вида есть переключатель
    // [species.<kind>] rankScale = off. Тогда ступень даёт атаку и крепость,
    // а размер остаётся ванильным: работает родной коридор вида и защита
    // крупных ванильных вожаков. Умолчание — включено (у гоблина как было).
    bool       scale;
    RankStep step[kRankSteps];
};

// Чтение из ini без зависимости от iniConfig: тот же приём, что у чисел вида.
struct RanksIniReader {
    virtual ~RanksIniReader() {}
    virtual float Float(const char* section, const char* key, float defValue) = 0;
    virtual bool  Bool (const char* section, const char* key, bool  defValue) = 0;
    // 85.57: имена наборов пачек. Не чисто виртуальный: наборы работают и без
    // имён (встроенные), а ломать уже собранные читатели из-за строки не хочется.
    virtual bool  Text (const char* section, const char* key, char* out, int cap)
    { (void)section; (void)key; (void)out; (void)cap; return false; }
};

// ── 85.57: НАБОРЫ (СЕТЫ) ПАЧЕК ПО МЕСТУ ────────────────────────────────────
//
// Владелец: «если все пачки в сессии будут одинаковыми по рангам, весь смысл
// теряется; в этой зоне такой сет, в следующей — другой».
//
// Так и было: каждая особь роллила ступень НЕЗАВИСИМО из общих весов, поэтому
// любая пачка выглядела статистически одинаково — три-четыре новичка, четыре-
// пять солдат, ветеран. Разница между пачками возникала только случайно.
//
// Ключ места — из ENCOUNTER_MEMORY_DESIGN §1: хеш ячейки карты
// (floor(x/cell), floor(z/cell)), высота не берётся (в подземельях этажи
// наложатся, но лучше объединить два боя в одной точке, чем считать их разными).
//
// Набор задаёт ОТНОСИТЕЛЬНЫЕ ВЕСА ступеней внутри пачки, а НЕ новые ступени:
// полосы размера, множитель атаки и крепость по-прежнему берутся из [ranks].
// То есть набор меняет СОСТАВ, а не силу отдельной особи.
// 85.57: четыре набора (rabble/patrol/warband/hunt) заполнены, два слота были
// про запас. 85.58: слотов 12 — владелец просил «расширить список для
// нестандартных сетов» под будущую FSM зон. Пустой слот = набор выключен
// (нулевой вес), поэтому старые ini работают без правок: лишние слоты просто
// не участвуют, пока владелец не задаст им вес и веса ступеней.
const int kPackSets = 12;

