#pragma once
/**
 * Лог в оперативке с непрерывным фоновым сбросом на диск и защитой при краше.
 * std::endl больше не трогает диск (только перевод строки в буфер).
 * Писатели с тика пешек и с кадра F12 сериализуются критической секцией.
 */
#include <ostream>
#include <windows.h>

namespace LogMem {

void Init();
// Идемпотентно. Из DllMain detach и из фильтра краша безопасно:
// только CreateFile/WriteFile, без повторной кучи сверх уже собранного буфера.
void FlushToDisk();
// Периодический сброс в фоновом потоке, чтобы диск всегда содержал свежий лог.
void PeriodicFlush(DWORD intervalMs = 1500);

// 85.25: сообщить обработчику сбоев, какой поток наш рабочий. Нужно, чтобы в
// строке сбоя было видно «наш это поток или чужой», а не гадать по косвенным.
void SetWorkerThreadId(DWORD tid);

// 85.25: сколько нарушений доступа перехвачено за сессию (для итоговой сводки).
unsigned VEH_Faults();
// 85.62: сколько раз сработала защита и сколько разных площадок найдено — для
// итоговой строки сессии, чтобы не печатать «[VEH] dump #N» на каждый случай.
unsigned VEH_Dumps();
unsigned VEH_Sites();

} // namespace LogMem

extern std::ostream logFile;
