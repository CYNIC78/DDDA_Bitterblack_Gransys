#pragma once
/**
 * 85.63: ПОЛЕВОЙ ПАКЕТ — сводки сессии одним блоком.
 *
 * ЗАЧЕМ. Сводки конца сессии рождаются в пяти модулях (пачка, агрессия, темп,
 * пешки, защита) и в разное время. В логе они поэтому стояли вразброс, между
 * чужими строками, и разбор сессии превращался в выискивание двадцати строк по
 * всему хвосту. Теперь каждая сводка кладётся в буфер печати (см. LogMem.cpp), а
 * Unitialize() выводит блок «=== SESSION ===» целиком — одним вырезаемым куском.
 *
 * ПОЧЕМУ ЗАГОЛОВОК ОТДЕЛЬНЫЙ, А НЕ В LogMem.h. LogMem.h объявляет `logFile` как
 * std::ostream, а шимы тестов (tools/tcomp) дают свой logFile как std::ofstream:
 * любой файл продукта, потянувший LogMem.h внутрь фикстуры, ломает сборку теста
 * на расхождении типов. Этому заголовку от мира нужны две функции и ничего
 * больше — поэтому он отдельный и ничего не подключает.
 *
 * ПРАВИЛА ДЛЯ ТОГО, КТО ЗОВЁТ:
 *   * SessionNote() — только то, что печатается ОДИН раз в конце сессии
 *     (сводки). Строки боя, события и предупреждения печатаются как раньше;
 *   * содержимое строки не меняется: пакет — это переезд, а не пересчёт;
 *   * SessionFlush() зовётся в Unitialize() ПОСЛЕ всех Shutdown() и до
 *     FlushToDisk(). Пока он не позван, строки лежат в памяти и в лог не попали.
 */
namespace LogMem {

void SessionNote(const char* line);

// 85.64: ОТКАТЫ. Строки вида «Errata[dagger-ban]: rolled back to vanilla (x2)»
// печатаются на месте (в середине сессии они тоже нужны — по ним видно, что
// откат прошёл именно тогда, когда прошёл) и ДОПОЛНИТЕЛЬНО собираются сюда:
// в конце сессии блок показывает, что успели вернуть к ванили, одним взглядом.
// Это не «перенос», а повтор: строка в подразделе помечена как повторённая.
void SessionNoteRollback(const char* line);

void SessionFlush();

} // namespace LogMem
