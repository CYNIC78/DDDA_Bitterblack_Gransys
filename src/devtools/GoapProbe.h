#pragma once
/**
 * GoapProbe — разведка планировщика пешки. ИССЛЕДОВАТЕЛЬСКИЙ инструмент.
 *
 * ЗАДАЧА. Понять, где в живом `cAIGoalPlanning` лежит набор доступных
 * действий, и есть ли там место для рывка. Это шаг 2 протокола из
 * `docs/PAWN_SPRINT_RECON.md`: только чтение, никаких правок.
 *
 * ЧТО УЖЕ ИЗВЕСТНО (Build 40, подтверждено дампами):
 *   cAIGoalPlanning              25264 B
 *   planner + 0x17C              код текущего выбранного приоритета
 *   PlanCtrl(code) = planner + 0x190 + code * 0x110
 *   код 1  = следовать за Воскресшим, код 54 = атака кинжалом
 *
 * ЧТО ИЩЕМ. В файлах `.gop` действие «рывок» отличается от «идти» ровно
 * одним числом — идентификатором моторной команды:
 *
 *   Follow           1     DashFollow      0xAD (173)
 *   DashFollowSt500  0xB0  PlEscape        0xB5 (181)
 *
 * В массив PlanCtrl такие числа не влезают (25264 байта хватает примерно
 * на 91 слот), значит это отдельное пространство идентификаторов команд.
 * Проба ищет эти числа в памяти планировщика и заодно составляет карту
 * его подобъектов по именам классов.
 *
 * ПОПРАВКА BUILD 73.27 — ОХОТА ЗА ЭТИМ ЧИСЛОМ БОЛЬШЕ НЕ НУЖНА.
 *
 * Фраза выше «хватает примерно на 91 слот» была догадкой, брошенной
 * вскользь. Она оказалась точным ответом: 0x190 + 91*0x110 = 25152 при
 * размере 25264 — ровно 91 слот и 112 байт хвоста. А массив загруженных
 * целей от planner+0x08 обрывается на слоте с кодом 90. Два числа сошлись,
 * и это значит: слот ресурса и слот PlanCtrl — одна и та же нумерация,
 * то есть КОД ПРИОРИТЕТА. Дальше см. блок «РАСШИФРОВКА КОДОВ».
 *
 * Идентификатор из .gop нам был нужен только как способ узнать «чем
 * рывок отличается от ходьбы». Теперь у нас есть номер самой цели —
 * ручка на уровень выше и без правки разобранных ресурсов.
 *
 * ЧТО УБРАНО (74.2). Пять кнопок-проб отработали свой вопрос и удалены
 * вместе с кодом — по правилу «вопрос → ответ → документ → удалить»:
 *
 *   Dump pawn planner        планировщик найден, путь записан (§18)
 *   Background walk          нужен был, чтобы его найти (§14, §16)
 *   Dump Arisen (stamina)    вопрос выносливости закрыт (§11, §15)
 *   Diff Follow vs DashFollow / Deep diff
 *                            искали идентификатор команды из .gop; он
 *                            больше не нужен — код цели это ручка
 *                            уровнем выше (§25)
 *
 * Осталось пять инструментов, и все пять отвечают на живые вопросы трека.
 */

#include <stdint.h>

namespace GoapProbe {

// Пути загруженных целей планировщика. Ресурсы rAIGoalPlanning — это
// файлы .gop, а у ресурса по +0x08 лежит путь. Отвечает на вопрос
// «есть ли DashFollow в наборе пешки» чтением имён.
//
// БОЛЬШЕ ТОГО (Build 73.27): номер слота в этом массиве И ЕСТЬ код
// приоритета. Дамп печатает код рядом с именем — см. ниже.
void DumpPlannerGoals();

// --- РАСШИФРОВКА КОДОВ (Build 73.27) ----------------------------------------
//
// Массив ресурсов целей идёт от planner+0x08 с шагом 4. Индекс слота —
// это и есть код приоритета:
//
//     code = (slotOffset - 8) / 4
//
// Четыре независимых подтверждения из прошлых сборок:
//     code  1 = Follow          (наблюдали живьём, Build 40)
//     code 15 = Air             (kGuardianModifiers, CONFIRMED)
//     code 54 = WpnDaggerAtk    (главный рычаг Guardian, CONFIRMED)
//     code 60 = Em0600Cover     (kGuardianModifiers, CONFIRMED)
//
// Пятое, структурное: старший загруженный слот — код 90 (DmgEscape),
// а в планировщик (25264 B) при базе 0x190 и шаге 0x110 влезает ровно
// 91 слот PlanCtrl, коды 0…90. Совпадение точное, без запаса.
//
// Отсюда сразу: DashFollow = код 84, DashFollowSt500 = 85,
// WpnSwordAtk = 52, WpnGSwordAtk = 53 (последние два закрывают дыру
// Guardian «работает только для кинжалов»).

// Сравнить блоки управления планом двух целей: PlanCtrl(1) «Follow»
// против PlanCtrl(84) «DashFollow».
//
// ЧЕМ ЭТО ЛУЧШЕ ДИФФА РЕСУРСОВ. Ресурсы — это разобранные файлы, каждый
// в своей области кучи, со своей раскладкой: сравнивать их по одинаковым
// смещениям бессмысленно. А PlanCtrl — элементы ОДНОГО массива одного
// типа: смещение k в обоих значит одно и то же поле. Это тот дифф,
// которым структурный обход должен был быть с самого начала.
void DumpPlanCtrlAB();

// Кто вообще может выбрать код 84. Дамп боевых «вёдер» приоритетного
// мышления (cAIPriorityThink) со всеми строками cPrioParam: код, кортеж
// и число правил, плюс имя цели рядом с кодом.
//
// ПОЧЕМУ ЭТО СЛЕДУЮЩИЙ ШАГ. Замер 73.27 ответил на развилку протокола:
// коды рывка 84/85 — ноль кадров и ноль входов, планировщик их не
// выбирает никогда. Значит дело не в исполнении, а в выборе. Выбор живёт
// не в планировщике, а в приоритетном мышлении: `cmc.prt` держит 85
// строк cPrioParam, и каждая строка — это «код + условия + веса».
//
// Вопрос, на который отвечает дамп, ровно один и он двоичный:
// ЕСТЬ ЛИ ВООБЩЕ СТРОКА С КОДОМ 84? От ответа зависит рычаг:
//   есть  -> строка проигрывает по весам, и рычагом становится тот самый
//            AddS32, которым мы уже транзакционно двигаем Guardian;
//   нет   -> цель загружена, но приоритетному мышлению недоступна, и
//            дешёвой правки весов не существует.
//
// Только чтение, по подтверждённым якорям (SOURCE_OF_TRUTH §3.2-3.4):
//   body -> cAICtrl -> cAIPriorityThink -> +0x38 + slot*0x14 (48 вёдер)
void DumpPriorityRows();

// Какие моторные интерфейсы вшиты в планы прямо сейчас: код 1 (Follow),
// 84 (DashFollow), 20 (Goto) и текущий выбранный код.
//
// ЗАЧЕМ. Замер 74.0: все рывки пешки — под кодом 1, строки приоритета у
// 84/85 нет вовсе. Значит развилка «бежать или рвануть» живёт ВНУТРИ
// цели Follow. Кнопка нажимается дважды — когда пешка спокойно бежит и
// когда рвётся, — и разница в списке интерфейсов показывает переключатель.
void DumpPlanInterfaces();

// Перекличка партии: все тела пешек (главная + наёмные) с их AI-корнями.
//
// ЗАЧЕМ ИМЕННО СЕЙЧАС. Наёмная пешка — тоже `uCmc`, и до 75.0 «главной»
// у нас считалось первое такое тело в порядке памяти. Кроме этого дампа
// нечем проверить, кого именно адресуют продуктовые модули.
//
// И главный вопрос, на который он отвечает: **ресурс приоритетов один на
// всех или свой у каждой пешки?** От ответа зависит область действия всех
// наших правок весов (доктрина Guardian уже пишет в правила):
//   один общий -> правки действуют на ВСЕХ пешек, включая чужих;
//   свой у каждой -> область ровно та, что мы выбираем.
void DumpPartyRoster();

// --- ТРЕК ИДЛОВ (docs/PAWN_IDLE_RECON.md) -----------------------------------
//
// Гистограмма ДЕЙСТВИЙ пешки (`cPlAct*`), а не целей: сколько кадров и
// сколько входов в каждое состояние, раздельно бой/покой.
//
// Зачем отдельно от гистограммы кодов. Код приоритета отвечает на вопрос
// «что пешка решила», действие — «что видно на экране». Заявка про идлы
// целиком про второе: сколько РАЗНЫХ состояний покоя у пешки вообще
// бывает и меняется ли их набор со сменой праймари-склонности.
//
// Порядок замера: `act watch` ON -> постоять пять минут -> `Act histogram`;
// затем сменить праймари и повторить. Разница списков и есть ответ.
void ToggleActWatch();
bool ActWatchActive();
void DumpActHistogram();

// ПОЛНАЯ КАРТА «СКЛОННОСТЬ → ЧТО ОНА ДВИГАЕТ».
//
// ЗАЧЕМ. Отзывы игроков про Guardian описывают три вещи: пешка липнет к
// игроку, бьёт только в ответ и бросает начатый каст ради перепозиции.
// Ни одна из них не про «штраф на атаку кинжалами» — а чинили мы именно
// его (code 54, rule[0], -3 -> 0).
//
// Причина слепоты в методе: аудит Build 57 был Guardian-scoped и смотрел
// на шесть заранее подозреваемых кодов, а последний дамп печатал только
// ЧИСЛО правил. Содержимое — `AddS32` и проверка `{склонность, ранг}` —
// лежит в тех же 85 строках и ни разу не было выписано целиком.
//
// Этот дамп раскрывает каждое правило личности каждой строки:
//   код + имя цели | AddS32 | break | склонность + ранг
// и в конце сводит по склонностям: что именно каждая из девяти двигает.
void DumpInclinationRules();

// КАРТА ВЁДЕР ВЫБРАННОЙ ПЕШКИ + ДИФФ С ПРЕДЫДУЩИМ СНИМКОМ.
//
// ЗАЧЕМ ЭТО ЗАКРЫВАЕТ ТУМАН. Правила приоритета лежат в ОБЩЕМ ресурсе
// (перекличка 75.11: три пешки, один `rAIPriorityThink` 0x5017AA90).
// А вот РАСКЛАДКА строк по 48 вёдрам живёт в инстансе `cAIPriorityThink`
// каждой пешки — и считается из её склонностей: базовый слот плюс
// `AddS32` тех правил, чьи проверки совпали.
//
// Значит «что Guardian делает ИМЕННО С ЭТОЙ пешкой» — это не рассуждение
// о правилах, а разница двух карт. Снял карту у Страйдерши-Guardian,
// снял у Файтера, сравнил: код 54 уехал на три ведра вниз — вот тебе
// штраф в чистом виде, увиденный, а не выведенный.
void DumpBucketMap();

// --- РАЗВЁРТКА ПО ВЁДРАМ (75.31) --------------------------------------------
// Протаскивает строку code 54 (WpnDaggerAtk) по всей шкале из 48 вёдер и в
// каждом положении считает долю боевых кадров в ближнем бою. Отвечает на
// вопрос «в каком ведре кинжалы начинают выигрывать у лука», то есть на
// вопрос о правиле соревнования МЕЖДУ группами вёдер — единственный, что
// сейчас отделяет нас от осмысленной правки правил.
//
// ПИШЕТ в игру (AddS32 первого правила code 54) и потому требует, чтобы
// галка Guardian-фикса была снята: у рычага не может быть двух хозяев.
// Ступень сменяется только по боевым кадрам, отчёт печатается сам.
void ToggleSlotSweep();
bool SlotSweepActive();
void DumpSweepReport();

// Гистограмма выбранных кодов. Слежение (code watch) считает, сколько
// кадров планировщик простоял в каждом коде, раздельно для боя и покоя.
// Отвечает числом на главный вопрос трека: выбирается ли код 84 вообще.
void DumpCodeHistogram();
void ResetCodeHistogram();

// Слежение за кодом текущего приоритета (planner + 0x17C): пишет в лог
// каждую смену. Так видно, какими кодами пешка реально пользуется в бою
// и вне боя — без этого непонятно, куда вообще вставлять рывок.
void ToggleCodeWatch();
bool CodeWatchActive();
// Какая пешка является целью всех проб: 0 — своя, 1..2 — наёмные.
// Набор целей планировщика зависит от вокации, поэтому «код 4 пуст» на
// своей пешке ничего не говорит о наёмном Файтере — цель надо выбирать.
void SetProbePawn(int idx);
int  GetProbePawn();

void Tick();

const char* Status();

} // namespace GoapProbe
