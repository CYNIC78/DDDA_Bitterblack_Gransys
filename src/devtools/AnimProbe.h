#pragma once
/**
 * AnimProbe — поиск множителя темпа анимации у существа. ИССЛЕДОВАТЕЛЬСКИЙ
 * инструмент.
 *
 * ЗАДАЧА. Найти поле, которым движок управляет скоростью проигрывания
 * анимации, и изменить темп атаки, не трогая ни урона, ни самой анимации.
 *
 * ЧТО УЖЕ ИСКЛЮЧЕНО (замеры билдов 20…35):
 *   - часов анимации (растущий счётчик кадров) в теле НЕТ: 20 смен действия,
 *     обход всего тела во float и в int, корреляция сбросов со сменой
 *     действия дала максимум 5 совпадений из 66 — это шум;
 *   - ровные периоды (1.00 с, 3.00 с, 4.00 с) — таймеры: настоящие
 *     длительности из .lmt неровные.
 *
 * ОТСЮДА СМЕНА ПОДХОДА. Множитель темпа — не пила, а КОНСТАНТА около 1.0,
 * которая не меняется, пока её не тронут. Поиск «того, что меняется» был
 * слеп к ней по определению. Теперь ищем то, что НЕ менялось ни разу.
 *
 * ТРИ СПОСОБА ПРОВЕРКИ, от дешёвого к дорогому:
 *
 *   1. ДЕЛЕНИЕ ПОПОЛАМ (Bisect). Кандидатов два десятка, драться с каждым
 *      по отдельности — это два десятка боёв. Вместо этого пишем значение
 *      сразу во ВСЕ и смотрим, изменился ли темп. Изменился — половиним
 *      набор, не изменился — берём другую половину. Пять боёв вместо
 *      двадцати четырёх, и первый же бой отвечает на главный вопрос:
 *      «а множитель вообще в этом списке?».
 *
 *   2. A/B ПО ТОРПОРУ (подсказка пользователя, сильнейший ход). Эффект
 *      torpor замедляет у монстра всё сразу — и анимацию, и физику. Значит
 *      движок УЖЕ умеет крутить нужную ручку, и она обязана лежать в памяти
 *      существа. Снимаем слепок обычного гоблина (A), накладываем торпор,
 *      снимаем слепок заторможенного (B) и печатаем поля, которые были
 *      неподвижны в обоих слепках, но изменили значение. Это не догадка,
 *      а прямое наблюдение за ручкой, которую дёргает сама игра.
 *
 *   3. Ручная запись в конкретное смещение — на добивание.
 *
 * ЧТО ЧИТАЕМ. Тело существа целиком (0x7400 B), объект текущего действия
 * (+0x2DC8) и один выбранный подобъект (watch child).
 *
 * ПИШЕТ В ИГРУ только по явному нажатию Apply, только в подопытное
 * существо и только пока проба активна. Исходные значения запоминаются
 * и возвращаются по Revert, по Stop и при смене набора.
 */

#include <stdint.h>

// Верхний уровень намеренно: вложенность в DevTools ничего не давала,
// зато заставляла писать DevTools::AnimProbe:: из файла, который сам
// внутри этого пространства не находится. Дважды поймались на C2653.
namespace AnimProbe {

// Перечислить дочерние объекты тела с именами классов через DTI.
void ScanChildren();

// Начать замер по конкретному телу. Пустой kind = первый попавшийся враг.
void Start(const char* kind);

// Дополнительно следить за дочерним объектом по смещению в теле.
// 0 = не следить.
void WatchChild(uint32_t bodyOffset);

// Остановить и выдать разбор в лог.
void Stop();

// Покадровый сэмпл. Зовётся из UI-колбэка, то есть каждый кадр.
void Tick();

bool        Active();
const char* Status();

// Вердикт последнего разбора: насколько изменились длительности действий
// по сравнению с предыдущим замером. Именно по нему отвечают «быстрее /
// без изменений» при делении пополам.
const char* Verdict();

// Кандидаты обхода подобъектов — по ним UI рисует кнопки «watch».
int         CandidateCount();
uint32_t    CandidateOffset(int i);
const char* CandidateName(int i);
uint32_t    WatchedOffset();

// --- кандидаты в множитель (константы ~1.0) --------------------------------
// Зона: 0 = тело, 1 = объект действия, 2 = подопечный подобъект.
int         ConstCount();
uint32_t    ConstOffset(int i);
float       ConstValue(int i);
const char* ConstZone(int i);

// --- проверка гипотезы записью ---------------------------------------------
// Пишет значение в поле и УДЕРЖИВАЕТ его каждый кадр: движок может
// переписывать поле, и разовая запись ничего не покажет.
// Подозреваемые в темпе анимации: поля, найденные дифом по торпору
// (0.5 в норме -> 0.25 под замедлением). Пишутся одной кнопкой.
int      SuspectCount();
uint32_t SuspectOffset(int i);
void     SuspectsApply(float value);

void  TestApplyIndex(int i, float value);        // по кнопке кандидата
void  TestWrite(uint32_t bodyOffset, float value); // ручное смещение в теле
void  TestRevert();
bool  TestActive();
int   TestHeldCount();                            // сколько полей удерживаем
const char* TestStatus();

// --- деление пополам --------------------------------------------------------
// Протокол: Begin -> бой -> Stop -> Report(изменился ли темп) -> Start ->
// бой -> Stop -> Report -> ... Набор сужается вдвое за раунд.
void        BisectBegin(float value);
void        BisectReport(bool effect);
void        BisectReset();
bool        BisectActive();
const char* BisectStatus();

// --- A/B сравнение (торпор) -------------------------------------------------
// which: 0 = A (норма), 1 = B (под эффектом), 2 = A2 (контроль, тоже норма).
//
// Контрольный слепок обязателен. Первый живой замер это доказал: без него
// в отчёт попали сорок «изменившихся» полей, которые были костями позы —
// существо просто стояло по-разному, а внутри одного слепка каждое такое
// поле идеально постоянно. Всё, что отличается уже между A и A2, — шум.
//
// Капчур длится kAbFrames кадров и завершается сам.
void        AbCapture(int which);

// Именованный дамп cCharParamEnemy (обе копии в теле). 72 поля из
// em0100_cmn.prp с ASCII-именами: res_TORPOR, RESTRAINT_SLOW_LV1 и прочие.
void        DumpCharParams();
bool        AbBusy();
bool        AbHave(int which);
void        AbCompare();
const char* AbStatus();

} // namespace AnimProbe
