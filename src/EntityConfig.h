#pragma once
/**
 * EntityConfig — настройки поведения сущностей из ddda_entities.ini.
 *
 * ГЛАВНАЯ ИДЕЯ: три уровня, значение наследуется сверху вниз.
 *
 *      [default]      <- один раз, действует на всех
 *          v
 *      [class.small]  <- на группу видов (мелочь, крупные, боссы)
 *          v
 *      [em0100]       <- на конкретный вид, если нужна точность
 *
 * Врагов 96 видов. Писать 96 секций руками невозможно и не нужно:
 * в файле лежит только то, что отличается от уровня выше.
 * Пустой файл = поведение ваниллы.
 *
 * HOT-RELOAD: раз в 500 мс сравнивается время модификации файла.
 * Чтение — только по факту изменения, никакого файлового I/O в тике.
 */

#include <windows.h>
#include <stdint.h>

class iniConfig;

namespace EntityCfg {

// ---- Значения на один вид врага -------------------------------------------
// Всё, что мы умеем менять. Множители, а не абсолюты: 1.0 = как в ванилле.
// Абсолютные значения (радиусы) держим в игровых единицах, 0 = не трогать.
struct Tuning {
    // зрение / слух  (.sn2: конус 60 гр / 1500, слух до 3000)
    float sightRadius;   // 0 = ваниль. Иначе абсолют, ед. игры
    float sightAngle;    // 0 = ваниль. Градусы. 60 ваниль, >120 убивает стелс
    float hearRadius;    // 0 = ваниль

    // темп действий (cMotionCtrl). ОПАСНО выше 1.5 — рассинхрон хитбокса
    float speedMin;      // нижняя граница разброса на особь
    float speedMax;      // верхняя

    // поводок / возврат домой (DDON Sanctuary)
    float leashScale;    // множитель радиуса возврата, 1.0 = ваниль
    float returnSpeed;   // множитель темпа на возврате (DDON-style рывок)
    bool  returnFight;   // огрызаться на отходе (ActThrowStone и т.п.)
    bool  returnArmor;   // DDON Sanctuary: многократная защита при возврате
    float returnArmorMult; // множитель физ/маг брони при возврате (напр. 4.0 = 400%)
    float returnDamageCut; // срез входящего урона (0.0..0.95)

    // размер особи (cCharParamEnemy +0x12C スケール値). 1.0 = ваниль.
    // Разброс на особь: заметно глазом мгновенно.
    float scaleMin;
    float scaleMax;
    // Неуниформность: движок держит W/H/D раздельно (+0x60/64/68).
    // 0 = все три одинаковы. 0.15 = ширина/глубина гуляют на +-15%
    // относительно высоты. Даёт коренастых и долговязых особей.
    float scaleJitter;

    bool  enabled;       // выключить мутации для этого вида целиком
};

// Границы. Значения из ini зажимаются сюда — защита от опечатки игрока.
struct Limits {
    static const int   kSightRadiusMax = 6000;
    static const int   kSightAngleMin  = 10;
    static const int   kSightAngleMax  = 360;
    static const int   kHearRadiusMax  = 8000;
};

float ClampSpeed(float v);   // 0.5 .. 1.5
float ClampScale(float v);   // 0.7 .. 1.4 — вне этого ломается хитбокс/анимация
float ClampAngle(float v);   // 10 .. 360
float ClampRadius(float v, float maxv);

// ---- Доступ ----------------------------------------------------------------

// Настройки для вида. emId — число из uEm0100 -> 100.
// Никогда не возвращает nullptr: если вида нет в ini, отдаёт [class.*]/[default].
const Tuning& For(uint16_t emId);

// Глобальный выключатель всего слоя мутаций.
bool Enabled();

// Разрешена ли ЗАПИСЬ в память. Отдельный флаг: конфиг можно читать
// и смотреть в UI, ничего не меняя. [global] allowWrites = off по умолчанию.
bool AllowWrites();

// Загрузить/перечитать. Вызывать при старте.
void Load();

// Тик: раз в 500 мс проверяет mtime и перечитывает при изменении.
// Дёшево — обычно это один GetFileAttributesEx.
void Tick();

// Явная перезагрузка (кнопка в F12-меню).
void ForceReload();

// Для UI: сколько раз перечитано и когда, чтобы видеть, что hot-reload живой.
int  ReloadCount();

} // namespace EntityCfg
