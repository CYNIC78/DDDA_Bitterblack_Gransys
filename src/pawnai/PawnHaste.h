#pragma once
/**
 * PawnAI::Haste — рывок пешки в бою через множитель передвижения.
 *
 * ЗАЧЕМ. У пешек в бою нет спринта вообще. Разведка GOAP показала
 * причину: даш существует отдельным действием, но привязан только к цели
 * Follow (догнать Аризена) и к Escape. На боевых целях его нет — значит
 * планировщику нечего выбрать (`docs/PAWN_SPRINT_RECON.md`).
 *
 * ЧТО ДЕЛАЕМ. Не трогаем планировщик. Берём тот же примитив, которым
 * ускоряем гоблинов, и на время поднимаем пешке множитель ПЕРЕДВИЖЕНИЯ.
 * Анимация остаётся джогом, но дистанция закрывается быстрее.
 *
 * ЭТО БОЛЬШЕ НЕ ПОДДЕЛКА (74.4). Ряд множителей воспроизведения нашёлся
 * и в теле пешки (замер 74.3: `1.000 x5` в покое, `1.060` на бегу —
 * первое поле ведёт сам движок). Со связкой `animCouple` ускоряется и
 * перемещение, и анимация бега, то есть проскальзывания стоп нет.
 *
 * И СМЫСЛ МОДУЛЯ ТОЖЕ ДРУГОЙ. Это не «баф пешке», а КОМПЕНСАЦИЯ за
 * ускоренных нами же монстров: пешке возвращается возможность
 * передислоцироваться под напором тех, кого мы разогнали. Поэтому при
 * `matchMonsterTempo = on` число берётся не из ini, а у самого быстрого
 * врага поблизости: монстры бегут ванильно — компенсации нет вовсе.
 *
 * ГДЕ ЖИВЁТ РЕШЕНИЕ. Здесь, на стороне пешек. Примитив темпа про бой
 * ничего не знает и знать не должен — он только применяет число.
 * Разговор идёт через Runtime::Tempo::SetOverride с коротким ttl:
 * перестали тикать — эффект сам погас.
 */

#include <stdint.h>

namespace PawnAI {
namespace Haste {

void Init();

// Зовётся из общего тика пешек (150 мс) под своим SEH.
void Tick();

void Shutdown();

// --- для панели -------------------------------------------------------------
struct Status {
    bool  enabled;
    bool  active;        // рывок применён прямо сейчас
    float factor;        // настроенный множитель
    float distM;         // до ближайшего врага, метры (-1 неизвестно)
    int   applied;       // сколько раз включали за сессию
    float used;          // множитель, применённый в последний раз
    bool  matchTempo;    // берём ли число у самых быстрых врагов рядом
    bool  requireWeapon; // гейт по обнажённому оружию пешки
    bool  animCouple;    // ускоряется ли анимация вместе с перемещением
    int   burstsWeapon;  // включений, подтверждённых обнажённым оружием
    int   burstsDetector;// включений, подтверждённых только детектором боя
    char  act[48];       // состояние пешки в момент последнего включения
    char  why[64];       // почему сейчас включено или нет
};
Status Get();
void   SetEnabled(bool on);
void   SetFactor(float f);
void   SetRequireWeapon(bool on);

} // namespace Haste
} // namespace PawnAI
