#pragma once
/**
 * PawnAI::DashWatch — наблюдатель за рывками пешки.
 *
 * ЗАЧЕМ. Мы собираемся вмешаться в набор действий планировщика. Прежде
 * чем что-то менять, нужен прибор, который отвечает на вопрос «пешка
 * рванула или нет» без споров и впечатлений. Он же станет приёмочным
 * тестом правки: до неё в бою нулей, после — не нулей.
 *
 * ЧТО НАБЛЮДАЕМ. У пешки есть собственные FSM-состояния движения, и
 * рывок среди них назван прямо:
 *
 *     cPlActDash, cPlActDashBegin, cPlActDashJump, cPlActDashJumpBegin
 *
 * Читаем текущее действие тела пешки (`+0x2DC8`, та же схема, что у
 * монстров — подтверждено дампами партии) и считаем переходы в эти
 * состояния, раздельно для боя и вне боя.
 *
 * ВТОРОЙ ПРИБОР. Счётчик хука спринта (`Tempo::GetSprintStats`) считает
 * тела, реально прошедшие через код спринтового перемещения. Два прибора
 * с разных сторон: один смотрит на намерение (FSM), другой на физику.
 * Если они разойдутся — это само по себе находка.
 *
 * ПРИБОРЫ РАЗОШЛИСЬ (замер 73.27) — И ЭТО ГЛАВНОЕ, ЧТО ОН ДАЛ.
 *
 * Гистограмма кодов приоритета за 118 секунд: коды рывка 84/85 — НОЛЬ
 * кадров, ноль входов. Планировщик рывок не выбирает никогда. А DashWatch
 * в том же сеансе поймал `cPlActDashBegin` дважды, причём один раз
 * В БОЮ (враг в 21 м, детектор боя = 1). Пешка рванула, не выбирая
 * кода рывка.
 *
 * Значит рывок приходит НЕ через код 84. Возможных объяснений два, и они
 * ведут в разные стороны:
 *   1) моторную команду рывка выбирает сама цель (например Follow, код 1)
 *      внутри своего плана — тогда наш рычаг это выбор интерфейса
 *      действия внутри цели, а код 84 вообще декорация;
 *   2) рывок запускает слой ниже планировщика (реакция FSM).
 *
 * Разделяет их одно число: КАКОЙ КОД БЫЛ АКТИВЕН В МОМЕНТ РЫВКА. Поэтому
 * DashWatch больше не смотрит на действие в одиночку: каждое событие
 * подписывается кодом приоритета (`Runtime::PawnPriorityCode`), именем
 * цели и показаниями счётчика хука спринта. Одно событие — все три
 * прибора в одной строке, без склейки логов по времени.
 *
 * ПРО ВЫНОСЛИВОСТЬ — ВОПРОС ЗАКРЫТ, ПРОБА УБРАНА. Поиск живого
 * `cPlStamina` в теле пешки не находил ничего и печатал это каждый
 * сеанс. Ответ известен (PAWN_SPRINT_RECON §11/§15): счётчик живёт в
 * записи персонажа, а не в теле, при этом правило расхода
 * `param\pl\stamina\PlStaminaDash` у пешки загружено. Порог St500
 * проходим, объяснять отсутствие рывка выносливостью нельзя.
 *
 * Только чтение. Ничего не пишет ни в игру, ни в конфиг.
 */

#include <stdint.h>

namespace PawnAI {
namespace DashWatch {

void Init();
void Tick();          // из общего тика пешек, 150 мс
void Shutdown();

struct Stats {
    uint32_t inCombat;        // рывков начато при живых врагах
    uint32_t outOfCombat;     // рывков начато без врагов
    uint32_t samples;         // сколько раз опрашивали
    float    lastDistM;       // до ближайшего врага в момент последнего рывка
    char     lastAct[48];     // текущее действие пешки
    char     lastDash[48];    // как называлось последнее пойманное состояние рывка

    // Сшивка с планировщиком: под каким кодом приоритета случился рывок.
    // Это и есть ответ на вопрос «откуда он берётся, если код 84 не
    // выбирается никогда».
    int32_t  lastCode;        // код приоритета в момент рывка (-1 = не читался)
    char     lastGoal[32];    // имя цели этого кода
    uint32_t dashUnderDash;   // рывков при коде 84/85 (DashFollow*)
    uint32_t dashUnderFollow; // рывков при коде 1 (Follow)
    uint32_t dashUnderOther;  // рывков при любом другом коде
    uint32_t dashCodeUnknown; // код прочитать не удалось
};
Stats Get();
void  Reset();

} // namespace DashWatch
} // namespace PawnAI
