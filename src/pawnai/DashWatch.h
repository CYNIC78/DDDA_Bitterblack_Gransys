#pragma once
/**
 * PawnAI::DashWatch — наблюдатель за рывками пешки.
 *
 * ЗАЧЕМ. Мы собираемся вмешаться в набор действий планировщика. Прежде
 * чем что-то менять, нужен прибор, который отвечает на вопрос «пешка
 * рванула или нет» без споров и впечатлений. Он же станет приёмочным
 * тестом правки: до неё в бою нулей, после — не нулей.
 *
 * ЧТО НАБЛЮДАЕМ. У пешки есть собственные FSM-состояния движения, и
 * рывок среди них назван прямо:
 *
 *     cPlActDash, cPlActDashBegin, cPlActDashJump, cPlActDashJumpBegin
 *
 * Читаем текущее действие тела пешки (`+0x2DC8`, та же схема, что у
 * монстров — подтверждено дампами партии) и считаем переходы в эти
 * состояния, раздельно для боя и вне боя.
 *
 * ВТОРОЙ ПРИБОР. Счётчик хука спринта (`Tempo::GetSprintStats`) считает
 * тела, реально прошедшие через код спринтового перемещения. Два прибора
 * с разных сторон: один смотрит на намерение (FSM), другой на физику.
 * Если они разойдутся — это само по себе находка.
 *
 * Только чтение. Ничего не пишет ни в игру, ни в конфиг.
 */

#include <stdint.h>

namespace PawnAI {
namespace DashWatch {

void Init();
void Tick();          // из общего тика пешек, 150 мс
void Shutdown();

struct Stats {
    uint32_t inCombat;        // рывков начато при живых врагах
    uint32_t outOfCombat;     // рывков начато без врагов
    uint32_t samples;         // сколько раз опрашивали
    float    lastDistM;       // до ближайшего врага в момент последнего рывка
    char     lastAct[48];     // текущее действие пешки
    char     lastDash[48];    // как называлось последнее пойманное состояние рывка
};
Stats Get();
void  Reset();

} // namespace DashWatch
} // namespace PawnAI
