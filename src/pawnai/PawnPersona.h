#pragma once
/**
 * PawnPersona — роль пешки из её СОБСТВЕННОГО стека склонностей.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Раньше доктрина выбирала «одного гвардиана на
 * партию» первым подходящим слотом (`GuardianDoctrine.cpp`, цикл
 * Main -> Hired1 -> Hired2 с `break`). Из-за этого Guardian-логика уходила
 * главной пешке, у которой Guardian числился лишь по ползунку, а наёмный
 * файтер с настоящим Guardian-первичной оставался ни с чем — и весь лог
 * теста показывал не ту пешку.
 *
 * Решение тестера: роль — свойство стека конкретной пешки, а не партии.
 * Пешек между собой мы не сравниваем, «главного гвардиана» не выбираем.
 * В партии может быть несколько гвардианов — каждый получит доктрину.
 *
 * ЧТО ЗДЕСЬ РЕШАЕТСЯ (docs/PAWN_ROLE_STACK.md):
 *   - ранг первее веса: правила cmc.prt стреляют по паре {склонность, ранг};
 *   - персоны две: Guardian / Nexus, при полном равенстве — Guardian;
 *   - порог годности: ранг не ниже secondary и значение не ниже порога.
 *
 * ЧИСТАЯ ЛОГИКА. Ни обращений к памяти игры, ни SEH, ни лога: поэтому
 * модуль целиком покрывается портируемым тестом без emulate-заглушек.
 */
#include "PawnAI_Common.h"

namespace PawnAI {
namespace Persona {

enum Kind {
    PERSONA_NONE = 0,   // пешка не гвардиан и не нексус
    PERSONA_GUARDIAN,
    PERSONA_NEXUS
};

// Ранг склонности в стеке пешки. Совпадает с нумерацией движка
// (SOURCE_OF_TRUTH.md §3.3): 2 = primary, 1 = secondary, 0 = tertiary.
// -1 = вне стека (значение не вошло в три верхних).
enum RankValue {
    RANK_OUT    = -1,
    RANK_THIRD  = 0,
    RANK_SECOND = 1,
    RANK_FIRST  = 2
};

// Раскладывает девять значений в ранги. Тай-брейк при равных значениях —
// меньший id склонности: решение детерминированное, игровой тай-брейк
// нам неизвестен и пока не проверялся (docs/PAWN_ROLE_STACK.md §3).
void RanksOf(const float values[9], int rankOut[9]);

// Кто эта пешка по своему стеку. rankOut / valueOut относятся к выбранной
// персоне и могут быть нулевыми указателями.
// ВАЖНО: годность (порог) НЕ проверяется — это делает вызывающий через
// Eligible(), потому что пороги настраиваются и у доктрин они разные.
Kind Of(const float values[9], int* rankOut = 0, float* valueOut = 0);

// Порог годности персоны.
inline bool Eligible(int rank, float value, int minRank, float minValue)
{
    return rank >= minRank && value >= minValue;
}

const char* Name(Kind k);

} // namespace Persona
} // namespace PawnAI
